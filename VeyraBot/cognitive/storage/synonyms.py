"""
查询扩展词表：让「换种说法」也能召回。

为什么需要它：
`vector_store` 用的是字符 2-gram + TF-IDF，字面重合才行。
用户问「你养的那只猫」而记忆里写的是「三花猫辣椒」时，
"猫"字对得上但"养"对不上，得分会被拉低到阈值以下（实测同类改写 query 得分 0.14~0.49）。

替代方案是本地 embedding 模型，但：
- `pip` 在本机不可用，装不了 sentence-transformers；
- DeepSeek 没有 embedding 接口；
- 动辄几百 MB 的模型文件对一个长期运行的小工程不划算。

所以用最省的办法补这一块：一张人工词表 + 查询扩展。
命中同组任一词，就把同组其他词一起拿来检索（权重打折，见 config.VECTOR_EXPAND_WEIGHT）。
它不是 embedding，但足以覆盖人设与日常话题里的常见改写。
"""
