def expand_terms(query: str, origin: str = "") -> List[str]:
    """
    根据查询（可选带上原始用户消息）扩展出同组词。

    :param query: 检索查询
    :param origin: 原始用户消息（可选，用于扩大命中面）
    :return: 去重后的扩展词列表（不含查询里已出现的词）
    """
    text = f"{query or ''} {origin or ''}"
    if not text.strip():
        return []

    hits: Dict[str, None] = {}
    for group in SYNONYM_GROUPS:
        if not any(term in text for term in group):
            continue
        for term in group:
            if term in text:
                continue
            hits[term] = None
    return list(hits.keys())
